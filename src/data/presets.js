function padOscillators(oscillators) {
  const padding = Array.from(
    { length: Math.max(0, OSCILLATOR_COUNT - oscillators.length) },
    () => DEFAULT_OSCILLATOR
  )
  return [...oscillators, ...padding]
}

export const PRESETS = PRESET_DEFINITIONS.map(({ globalFilter, oscillators, ...meta }) => ({
  ...meta,
  data: { globalFilter, oscillators: padOscillators(oscillators) },
}))
